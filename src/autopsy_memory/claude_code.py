"""Claude Code transcripts -> conversation exchanges.

A Claude Code session transcript (``~/.claude/projects/<project>/<session>.jsonl``)
is mostly machinery: tool results, thinking, API bookkeeping, attachments. What a
person remembers is the conversation: what they asked, what was said back, and
what was touched along the way. This module turns a transcript into exactly
that, one *exchange* per human prompt:

- the prompt (plus anything typed mid-turn),
- Claude's visible replies (no thinking, no tool output),
- the files read or changed and the tools used,
- timestamps for the start and end of the exchange.

Keys are stable across a live, growing transcript: the session is keyed by its
session id and each exchange by its prompt's uuid, so re-reading the file
updates the last exchange in place and appends new ones. Context-compaction
summaries are kept as their own exchanges: they are dense, already-curated
recaps of everything before them.

The parser is pure (no graph access) so it can be tested and reused.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any, Iterable

SOURCE_LABELS = {"claude-code", "claude_code", "codex"}
# Bump when the stored shape of an exchange changes: every exchange is rewritten once.
FORMAT_VERSION = 3

# Prompts that are machinery, not something a person typed.
_MACHINE_PREFIXES = (
    "<task-notification>",
    "<local-command",
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "<user-memory-input>",
    "<side-sessions-event>",
    "<ci-monitor-event>",
    "Caveat: The messages below were generated by the user while running local commands",
    "[Request interrupted",
)
_SYSTEM_REMINDER = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
# Context blocks that hosts (IDEs, ContextOS) put in front of the user's words:
# <canvas-thread>…</canvas-thread>, <workspace …>…</workspace>, <ide_selection>…
_LEADING_BLOCK = re.compile(r"^\s*<([A-Za-z][\w-]*)(?:\s[^>]*)?>(.*?)</\1>\s*", re.S)
_FILE_TOOLS = {"Read", "Edit", "Write", "MultiEdit", "NotebookEdit", "NotebookRead"}
_ASSISTANT_LIMIT = 6000
_PROMPT_LIMIT = 4000
_FILE_LIMIT = 40


def _clean(text: str) -> str:
    return _SYSTEM_REMINDER.sub("", text or "").strip()


# Wrappers hosts put around the person's own words (ContextOS orchestrators get
# <person-message id=…>…</person-message>); the words inside are the prompt.
_WORDS_WRAPPER = re.compile(r"^\s*<(person-message|person-said)\b[^>]*>\s*(.*?)\s*</\1>\s*$", re.S)
_TAG_LINE = re.compile(r"^\s*</?[A-Za-z][\w-]*(?:\s[^>]*)?>\s*$")


def _own_words(text: str) -> str:
    """A project thread's wake (<wake>…<message from="human">…</message>…) or a
    coordinator relay quoting the person (<cited author="user">) carries the
    person's words inside machinery: keep only those words."""
    if "<wake" not in text and "<relay" not in text:
        return text
    parts = re.findall(r'<message\b[^>]*from="human"[^>]*>(.*?)</message>', text, re.S)
    parts += re.findall(r'<cited author="user">(.*?)</cited>', text, re.S)
    note = re.findall(r"<note>(.*?)</note>", text, re.S)
    words = "\n\n".join(re.sub(r"<[^>]+>", " ", part).strip() for part in parts if part.strip())
    if not words and note:            # a relay with only another agent's note: keep the note
        words = re.sub(r"<[^>]+>", " ", note[0]).strip()
    return words or text


def _split_context(text: str) -> tuple[str, str]:
    """Separate leading host context blocks from what the person actually typed."""
    context = []
    rest = _own_words(text)
    while True:
        match = _LEADING_BLOCK.match(rest)
        if not match or match.end() >= len(rest):
            break
        context.append(match.group(0).strip())
        rest = rest[match.end():]
    wrapped = _WORDS_WRAPPER.match(rest)
    if wrapped:
        rest = wrapped.group(2)
    return rest.strip(), "\n".join(context)


def _prompt_text(content: Any) -> str:
    if isinstance(content, str):
        return _clean(content)
    if isinstance(content, list):
        parts = []
        for block in content:
            if not isinstance(block, dict):
                continue
            if block.get("type") == "text":
                parts.append(str(block.get("text") or ""))
            elif block.get("type") == "image":
                parts.append("[image]")
        return _clean("\n".join(parts))
    return ""


def _is_tool_result(content: Any) -> bool:
    return isinstance(content, list) and any(
        isinstance(block, dict) and block.get("type") == "tool_result" for block in content
    )


def _is_machine(text: str) -> bool:
    return not text or text.startswith(_MACHINE_PREFIXES)


def _clip_middle(text: str, limit: int) -> str:
    if len(text) <= limit:
        return text
    head = limit // 4
    tail = limit - head - 5
    return text[:head].rstrip() + "\n[…]\n" + text[-tail:].lstrip()


def _tool_files(name: str, tool_input: Any) -> list[str]:
    if not isinstance(tool_input, dict):
        return []
    files = []
    if name in _FILE_TOOLS:
        for key in ("file_path", "notebook_path", "path"):
            value = tool_input.get(key)
            if isinstance(value, str) and value.startswith("/"):
                files.append(value)
    return files


class _Exchange:
    __slots__ = ("uuid", "started", "ended", "prompt", "context", "followups", "replies", "files", "tools", "kind", "cwd", "branch")

    def __init__(self, uuid: str, started: str, prompt: str, kind: str = "exchange", cwd: str = "", branch: str = ""):
        self.uuid = uuid
        self.started = started
        self.ended = started
        self.prompt = prompt
        self.context = ""
        self.followups: list[str] = []
        self.replies: list[str] = []
        self.files: list[str] = []
        self.tools: dict[str, int] = {}
        self.kind = kind
        self.cwd = cwd
        self.branch = branch

    def touch(self, timestamp: str) -> None:
        if timestamp and timestamp > (self.ended or ""):
            self.ended = timestamp

    def add_file(self, path: str) -> None:
        if path not in self.files and len(self.files) < _FILE_LIMIT:
            self.files.append(path)

    def payload(self, index: int, agent: str = "Claude") -> dict[str, Any]:
        reply = _clip_middle("\n\n".join(r for r in self.replies if r).strip(), _ASSISTANT_LIMIT)
        prompt = _clip_middle(self.prompt, _PROMPT_LIMIT)
        if self.kind == "summary":
            text = "Summary of the conversation so far:\n\n" + prompt
        else:
            lines = [f"User: {prompt}"]
            for followup in self.followups:
                lines.append(f"User (while {agent} worked): {_clip_middle(followup, 1500)}")
            if reply:
                lines.append(f"{agent}: {reply}")
            text = "\n\n".join(lines)
        if self.files:
            text += "\n\nFiles: " + ", ".join(self.files)
        if self.context:
            text += "\n\nContext given with the prompt:\n" + _clip_middle(self.context, 1500)
        tools = dict(sorted(self.tools.items(), key=lambda kv: (-kv[1], kv[0])))
        digest = hashlib.sha1(
            json.dumps([FORMAT_VERSION, text, tools, self.ended], sort_keys=True).encode("utf-8")
        ).hexdigest()
        return {
            "uuid": self.uuid,
            "index": index,
            "kind": self.kind,
            "started": self.started,
            "ended": self.ended,
            "prompt": prompt,
            "reply": reply,
            "text": text,
            "files": list(self.files),
            "context": self.context,
            "tools": tools,
            "cwd": self.cwd,
            "branch": self.branch,
            "sha": digest,
        }


def parse_transcript(lines: Iterable[str]) -> dict[str, Any]:
    """Parse a Claude Code JSONL transcript into session info and exchanges."""
    session_id = ""
    title = ""
    first_prompt = ""
    cwd = ""
    branch = ""
    started = ""
    ended = ""
    exchanges: list[_Exchange] = []
    current: _Exchange | None = None
    errors = 0
    for line in lines:
        line = line.strip()
        if not line:
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            errors += 1
            continue
        if not isinstance(entry, dict):
            continue
        kind = entry.get("type")
        session_id = session_id or str(entry.get("sessionId") or "")
        if kind == "custom-title" and entry.get("customTitle"):
            title = str(entry["customTitle"])
            continue
        if kind == "summary" and entry.get("summary") and not title:
            title = str(entry["summary"])
            continue
        timestamp = str(entry.get("timestamp") or "")
        if timestamp:
            started = started or timestamp
            ended = max(ended, timestamp)
        if entry.get("isSidechain"):
            continue
        if kind == "user":
            cwd = str(entry.get("cwd") or cwd)
            branch = str(entry.get("gitBranch") or branch)
            message = entry.get("message") or {}
            content = message.get("content")
            if _is_tool_result(content):
                if current:
                    current.touch(timestamp)
                continue
            text = _prompt_text(content)
            if entry.get("isCompactSummary"):
                summary = text.split("Summary:", 1)[-1].strip() if "Summary:" in text else text
                exchanges.append(_Exchange(str(entry.get("uuid") or ""), timestamp, summary, kind="summary", cwd=cwd, branch=branch))
                # Compaction happens mid-turn: what follows still answers the last prompt.
                continue
            if entry.get("isMeta") or _is_machine(text):
                continue
            text, context = _split_context(text)
            current = _Exchange(str(entry.get("uuid") or ""), timestamp, text, cwd=cwd, branch=branch)
            current.context = context
            exchanges.append(current)
            first_prompt = first_prompt or text
            continue
        if kind == "attachment":
            attachment = entry.get("attachment") or {}
            if attachment.get("type") == "queued_command" and current:
                text = _clean(str(attachment.get("prompt") or ""))
                if not _is_machine(text):
                    current.followups.append(text)
                    current.touch(timestamp)
            continue
        if kind == "assistant" and current:
            current.touch(timestamp)
            for block in (entry.get("message") or {}).get("content") or []:
                if not isinstance(block, dict):
                    continue
                if block.get("type") == "text":
                    text = _clean(str(block.get("text") or ""))
                    if text:
                        current.replies.append(text)
                elif block.get("type") == "tool_use":
                    name = str(block.get("name") or "tool")
                    current.tools[name] = current.tools.get(name, 0) + 1
                    for path in _tool_files(name, block.get("input")):
                        current.add_file(path)
    payloads = [exchange.payload(index) for index, exchange in enumerate(exchanges, start=1) if exchange.uuid]
    return {
        "session_id": session_id,
        "title": title or (first_prompt.splitlines()[0][:120] if first_prompt else ""),
        "first_prompt": first_prompt,
        "cwd": cwd,
        "branch": branch,
        "started": started,
        "ended": ended,
        "exchanges": payloads,
        "parse_errors": errors,
    }


_CODEX_PATCH_FILE = re.compile(r"^\*\*\* (?:Update|Add|Delete) File: (.+)$", re.M)


def parse_codex_rollout(lines: Iterable[str]) -> dict[str, Any]:
    """Parse a Codex rollout (``~/.codex/sessions/YYYY/MM/DD/rollout-*.jsonl``)
    into the same shape as :func:`parse_transcript`: one exchange per prompt the
    person typed, with Codex's visible replies, the tools it ran and the files
    its patches touched."""
    session_id = cwd = branch = started = ended = first_prompt = ""
    exchanges: list[_Exchange] = []
    current: _Exchange | None = None
    errors = 0
    for line in lines:
        line = line.strip()
        if not line:
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            errors += 1
            continue
        if not isinstance(entry, dict):
            continue
        kind = entry.get("type")
        payload = entry.get("payload") if isinstance(entry.get("payload"), dict) else {}
        timestamp = str(entry.get("timestamp") or "")
        if timestamp:
            started = started or timestamp
            ended = max(ended, timestamp)
        if kind == "session_meta":
            session_id = session_id or str(payload.get("id") or "")
            cwd = str(payload.get("cwd") or cwd)
            git = payload.get("git") if isinstance(payload.get("git"), dict) else {}
            branch = str(git.get("branch") or branch)
            continue
        if kind == "turn_context":
            cwd = str(payload.get("cwd") or cwd)
            continue
        if kind != "response_item":
            continue
        item_type = payload.get("type")
        if item_type == "message":
            texts = [str(part.get("text") or "") for part in payload.get("content") or []
                     if isinstance(part, dict) and part.get("type") in ("input_text", "output_text")]
            text = _clean("\n".join(t for t in texts if t))
            role = payload.get("role")
            if role == "user":
                # environment / instructions blocks the app sends are machinery
                if not text or text.startswith("<") or _is_machine(text):
                    continue
                text, context = _split_context(text)
                uid = "codex-" + hashlib.sha1(f"{timestamp}|{text[:200]}".encode("utf-8")).hexdigest()[:16]
                current = _Exchange(uid, timestamp, text, cwd=cwd, branch=branch)
                current.context = context
                exchanges.append(current)
                first_prompt = first_prompt or text
            elif role == "assistant" and current and text:
                current.replies.append(text)
                current.touch(timestamp)
            continue
        if current and item_type in ("custom_tool_call", "function_call", "local_shell_call"):
            name = str(payload.get("name") or item_type)
            current.tools[name] = current.tools.get(name, 0) + 1
            current.touch(timestamp)
            raw = str(payload.get("input") or payload.get("arguments") or "")
            for match in _CODEX_PATCH_FILE.finditer(raw):
                path = match.group(1).strip()
                if path and not path.startswith("/") and cwd:
                    path = f"{cwd.rstrip('/')}/{path}"
                if path.startswith("/"):
                    current.add_file(path)
    payloads = [exchange.payload(index, agent="Codex") for index, exchange in enumerate(exchanges, start=1)]
    return {
        "session_id": session_id,
        "title": first_prompt.splitlines()[0][:120] if first_prompt else "",
        "first_prompt": first_prompt,
        "cwd": cwd,
        "branch": branch,
        "started": started,
        "ended": ended,
        "exchanges": payloads,
        "parse_errors": errors,
        "harness": "codex",
    }


def is_codex_rollout(path: str | Path) -> bool:
    path = Path(path)
    if path.name.startswith("rollout-"):
        return True
    try:
        with path.open("r", encoding="utf-8", errors="replace") as handle:
            head = json.loads(handle.readline() or "{}")
        return isinstance(head, dict) and head.get("type") == "session_meta"
    except Exception:
        return False


def parse_transcript_file(path: str | Path) -> dict[str, Any]:
    path = Path(path)
    codex = is_codex_rollout(path)
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        parsed = parse_codex_rollout(handle) if codex else parse_transcript(handle)
    parsed["session_id"] = parsed["session_id"] or path.stem
    parsed.setdefault("harness", "claude-code")
    return parsed


PASSAGE_CHARS = 900


def split_passages(text: str, size: int = PASSAGE_CHARS) -> list[str]:
    """Split an exchange into passages of about ``size`` characters at paragraph
    boundaries, so each one can be embedded and reranked whole (an exchange can
    run to thousands of characters and cover several topics)."""
    paragraphs = [part.strip() for part in re.split(r"\n\s*\n", text or "") if part.strip()]
    passages: list[str] = []
    current = ""
    for paragraph in paragraphs:
        while len(paragraph) > size * 2:  # one huge paragraph: cut at a sentence/space near the limit
            cut = max(paragraph.rfind(". ", 0, size), paragraph.rfind(" ", 0, size))
            cut = cut + 1 if cut > size // 2 else size
            if current:
                passages.append(current)
                current = ""
            passages.append(paragraph[:cut].strip())
            paragraph = paragraph[cut:].strip()
        if current and len(current) + len(paragraph) + 2 > size:
            passages.append(current)
            current = ""
        current = f"{current}\n\n{paragraph}".strip()
    if current:
        passages.append(current)
    return passages


SESSION_KEY_PREFIX = {"claude-code": "claude-session", "codex": "codex-session"}


def session_stable_key(session_id: str, harness: str = "claude-code") -> str:
    return f"{SESSION_KEY_PREFIX.get(harness, 'claude-session')}:{session_id}"


def exchange_stable_key(session_id: str, exchange_uuid: str, harness: str = "claude-code") -> str:
    return f"{session_stable_key(session_id, harness)}#{exchange_uuid}"


def exchange_label(session_title: str, exchange: dict[str, Any]) -> str:
    if exchange.get("kind") == "summary":
        return f"Recap · {session_title}"[:140]
    lines = [line for line in (exchange.get("prompt") or "").strip().splitlines()
             if line.strip() and not _TAG_LINE.match(line)]
    head = re.sub(r"<[^>]+>", "", lines[0]).strip() if lines else ""
    return (head[:110] + "…") if len(head) > 110 else head or session_title[:140]
